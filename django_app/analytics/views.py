"""
analytics/views.py — Overview, preprocessing, and visualizations views.
"""

import json
import os
from pathlib import Path

from django.conf import settings
from django.contrib import messages
from django.contrib.auth.decorators import login_required
from django.http import FileResponse, Http404
from django.shortcuts import render

from datasets.models import Dataset
from datasets.services import read_dataframe

from .services import NumpyEncoder, get_all_chart_data, preprocessing_summary


def _get_user_dataset(request):
    """Return user's latest validated dataset and its DataFrame, or (None, None)."""
    dataset = (
        Dataset.objects.filter(user=request.user, status=Dataset.STATUS_VALIDATED)
        .order_by("-upload_date")
        .first()
    )
    if not dataset:
        return None, None
    try:
        with open(dataset.uploaded_file.path, "rb") as f:
            df = read_dataframe(f, dataset.filename())
        return dataset, df
    except Exception as e:
        return dataset, None


def _viz_files() -> list:
    """Return list of (filename, url) for existing visualisation PNGs."""
    viz_dir = settings.ML_VIZ_DIR
    result = []
    for fname in sorted(viz_dir.glob("*.png")):
        result.append({
            "name": fname.stem.replace("_", " ").title(),
            "filename": fname.name,
            "path": str(fname),
        })
    return result


@login_required
def overview_view(request):
    """High-level dataset overview with chart.js charts."""
    dataset, df = _get_user_dataset(request)

    chart_data = {}
    if df is not None:
        chart_data = get_all_chart_data(df)

    context = {
        "dataset":          dataset,
        "chart_data_json":  json.dumps(chart_data, cls=NumpyEncoder),
        "has_dataset":      df is not None,
    }
    return render(request, "analytics/overview.html", context)


@login_required
def preprocessing_view(request):
    """Preprocessing stats — before/after summary for the uploaded dataset."""
    dataset, df = _get_user_dataset(request)

    summary = {}
    if df is not None:
        summary = preprocessing_summary(df)

    context = {
        "dataset": dataset,
        "summary": summary,
        "has_dataset": df is not None,
        "pipeline_steps": PIPELINE_STEPS,
    }
    return render(request, "analytics/preprocessing.html", context)


@login_required
def visualizations_view(request):
    """
    Display EDA visualisations.
    Shows static images generated by the offline pipeline (src/eda.py).
    """
    viz_list = _viz_files()

    context = {
        "viz_files":  viz_list,
        "has_images": len(viz_list) > 0,
    }
    return render(request, "analytics/visualizations.html", context)


# Pipeline steps shown on the preprocessing page
PIPELINE_STEPS = [
    ("Drop Loan_ID", "Remove identifier — no predictive value"),
    ("Encode Target", "Y → 1 (Approved), N → 0 (Rejected)"),
    ("Median Impute", "Numeric NaN → column median"),
    ("Mode Impute", "Categorical NaN → most frequent value"),
    ("Drop Duplicates", "Remove exact duplicate rows"),
    ("IQR Cap Outliers", "Winsorise ApplicantIncome, LoanAmount, CoapplicantIncome"),
    ("Stratified Split", "80% train / 20% test, stratify on target"),
    ("StandardScaler", "Zero-mean, unit-variance on numeric features"),
    ("OneHotEncoder", "Binary columns for categorical features"),
]


@login_required
def viz_image_view(request, filename):
    """Serve a visualisation PNG from the visualizations/ directory."""
    viz_dir = settings.ML_VIZ_DIR
    # Sanitise: only allow .png files and no directory traversal
    safe_name = Path(filename).name
    if not safe_name.endswith(".png"):
        raise Http404("Only PNG files are served here.")
    filepath = viz_dir / safe_name
    if not filepath.exists():
        raise Http404(f"Image '{safe_name}' not found.")
    return FileResponse(open(filepath, "rb"), content_type="image/png")
